import { loadConfig } from "@codesentra/config";
import { createDatabase } from "@codesentra/db";
import type { QueueClient, RunEventListener } from "@codesentra/queue";
import { buildApp } from "./app.js";
import { createAuthService } from "./auth/service.js";
import { createAuthz } from "./authz.js";

interface OpenApiDoc {
  info: { title: string; version: string; description?: string };
  paths: Record<
    string,
    Record<
      string,
      {
        summary?: string;
        description?: string;
        tags?: string[];
        responses?: Record<string, unknown>;
      }
    >
  >;
}

const unused = new Proxy(
  {},
  {
    get() {
      throw new Error("not available while generating the OpenAPI document");
    },
  },
);

/** Builds the app with inert dependencies (nothing connects) and returns its OpenAPI document. */
export async function generateOpenApi(): Promise<OpenApiDoc> {
  const config = loadConfig("api", {
    NODE_ENV: "test",
    DATABASE_URL: "postgres://openapi:unused@127.0.0.1:1/openapi",
    SESSION_SECRET: "openapi-generation-session-secret-not-used",
    ENCRYPTION_KEY: Buffer.alloc(32, 1).toString("base64"),
    PUBLIC_APP_URL: "http://localhost:3000",
  });
  const db = createDatabase(config.DATABASE_URL, { max: 1 });
  const { app } = await buildApp({
    config,
    db,
    auth: createAuthService(db),
    authz: createAuthz(db),
    queue: unused as QueueClient,
    events: unused as RunEventListener,
    email: null,
    store: null,
    cookie: { secure: false },
    fetch,
  });
  const doc = app.swagger() as unknown as OpenApiDoc;
  await app.close();
  await db.close();
  return doc;
}

const METHODS = ["get", "post", "patch", "put", "delete"];

/** Markdown reference generated from the OpenAPI document (docs/api.md). */
export function renderApiMarkdown(doc: OpenApiDoc): string {
  const lines = [
    `# ${doc.info.title} ${doc.info.version}`,
    "",
    "<!-- Generated by `pnpm --filter @codesentra/api openapi`. Do not edit by hand. -->",
    "",
    doc.info.description ?? "",
    "",
    "Machine-readable spec: [`openapi.json`](openapi.json) (also served at `GET /v1/openapi.json`).",
    "",
    "| Method | Path | Summary | Responses |",
    "|---|---|---|---|",
  ];
  for (const path of Object.keys(doc.paths).sort()) {
    const ops = doc.paths[path] ?? {};
    for (const method of METHODS) {
      const op = ops[method];
      if (!op) continue;
      const codes = Object.keys(op.responses ?? {})
        .sort()
        .join(", ");
      lines.push(
        `| ${method.toUpperCase()} | \`${path}\` | ${(op.summary ?? "").replace(/\|/g, "\\|")} | ${codes} |`,
      );
    }
  }
  lines.push("");
  return lines.join("\n");
}
