/**
 * Rule 5 / ADR 0030: a scanned repository's code never runs while the network is on. Each
 * case is a hostile repository whose package-manager hooks write a marker file and call a
 * canary server. The sandbox is wrapped so that, after every container, the markers in its
 * workdir are recorded with the network that container had: a marker seen after a networked
 * container means repository code ran with the network.
 */

