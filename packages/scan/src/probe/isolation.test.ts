function walkMarkers(dir: string): string[] {
  const out: string[] = [];
  const walk = (d: string) => {
    let names: string[];
    try {
      names = readdirSync(d);
    } catch {
      return;
    }
    for (const n of names) {
      const p = join(d, n);
      if (n.startsWith("HOSTILE_RAN-")) out.push(n);
      try {
        if (statSync(p).isDirectory()) walk(p);
      } catch {}
    }
  };
  walk(dir);
  return out.sort();
}

function viewOf(dir: string): ProjectView {
  const files = new Set<string>();
  const walk = (d: string, rel: string) => {
    for (const n of readdirSync(d)) {
      const p = join(d, n);
      const r = rel ? `${rel}/${n}` : n;
      if (statSync(p).isDirectory()) walk(p, r);
      else files.add(r);
    }
  };
  walk(dir, "");
  return {
    files,
    read: (p) => {
      try {
        return readFileSync(join(dir, p), "utf8");
      } catch {
        return null;
      }
    },
  };
}

/** The address a fetch container uses to reach a server on this host. */
function hostAddress(network: string): string {
  if (network === "host") return "127.0.0.1";
  try {
    const gw = execFileSync(
      "docker",
      ["network", "inspect", network, "-f", "{{range .IPAM.Config}}{{.Gateway}} {{end}}"],
      { encoding: "utf8" },
    )
      .trim()
      .split(/\s+/)[0];
    return gw || "172.17.0.1";
  } catch {
    return "172.17.0.1";
  }
}

describe("no repository code runs with the network (Rule 5, ADR 0030)", () => {
  let base: Sandbox;
  let canary: Server;
  let canaryUrl = "";
  const hits: string[] = [];
  const scratch: string[] = [];

  beforeAll(async () => {
    if (!process.env.SANDBOX_IMAGE)
      execFileSync("docker", ["build", "-q", "-t", IMAGE, join(ROOT, "infra/sandbox")], {
        stdio: "pipe",
        timeout: 600_000,
      });
    base = await createSandbox({
      network: FETCH_NETWORK,
      proxy: process.env.SANDBOX_FETCH_PROXY ?? null,
      caFile: process.env.SANDBOX_FETCH_CA_FILE ?? null,
    });
    canary = createServer((req, res) => {
      hits.push(req.url ?? "");
      res.writeHead(404).end();
    });
    await new Promise<void>((ok) => canary.listen(0, "0.0.0.0", ok));
    canaryUrl = `http://${hostAddress(FETCH_NETWORK)}:${(canary.address() as AddressInfo).port}`;
  }, 660_000);
  afterAll(() => {
    canary?.close();
    for (const d of scratch) rmSync(d, { recursive: true, force: true });
  });

  it.each(CASES.map((c) => [c.name, c] as const))(
    "%s",
    async (_n, c) => {
      const dir = mkdtempSync(join(tmpdir(), "cs-hostile-"));
      scratch.push(dir);
      const src = join(dir, "src");
      for (const [p, text] of Object.entries(c.files(canaryUrl))) {
        mkdirSync(dirname(join(src, p)), { recursive: true });
        writeFileSync(join(src, p), text);
      }
      const seen: { network: string; markers: string[] }[] = [];
      const sandbox: Sandbox = {
        runtime: base.runtime,
        async run(o) {
          const r = await base.run(o);
          seen.push({ network: o.network ?? "none", markers: walkMarkers(o.workdir) });
          return r;
        },
      };
      const before = hits.length;
      const run = await runProbes({
        sandbox,
        image: IMAGE,
        sourceDir: src,
        scratchDir: join(dir, "scratch"),
        plan: planProbes(viewOf(src)),
      });
      // Give a late request from a detached payload time to arrive.
      await new Promise((ok) => setTimeout(ok, 500));
      const ctx = JSON.stringify(
        {
          seen,
          fetch: { ...run.fetch, excerpt: run.fetch.excerpt.slice(-1200) },
          results: run.results.map((r) => ({ ...r, excerpt: r.excerpt.slice(-600) })),
        },
        null,
        1,
      );
      expect(
        seen.filter((s) => s.network !== "none" && s.markers.length),
        `repository code ran with the network\n${ctx}`,
      ).toEqual([]);
      expect(hits.slice(before), `the canary was reached\n${ctx}`).toEqual([]);
      expect(run.fetch.status, ctx).toBe(c.expect.fetch);
      if (c.expect.reasonMatches)
        expect(run.fetch.reason ?? "", ctx).toMatch(c.expect.reasonMatches);
      if (c.expect.install)
        expect(run.results.find((r) => r.name === "install")?.status, ctx).toBe(c.expect.install);
    },
    10 * 60_000,
  );
});
